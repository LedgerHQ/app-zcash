def _distinct_spends(pool, dummy_first):
    """Combine existing valid notes with different rho/rseed/nullifiers and alpha."""
    if pool == "orchard":
        bundle = _mixed_real_and_dummy_orchard_bundle()
        first = _valid_orchard_bundle().actions[0]
    else:
        bundle = _ironwood_bundle_with_external_recipient()
        first = _valid_ironwood_action()
    second, dummy = bundle.actions
    # Existing second.rk uses alpha=1. Add G to get the public alpha=2 key.
    second.alpha = (2).to_bytes(32, "little")
    second.rk = _alpha_2_rk(second.rk)
    assert first.nullifier != second.nullifier and first.spend_rho != second.spend_rho
    assert first.rk != second.rk
    bundle.actions = ([dummy] if dummy_first else []) + [first, second]
    bundle.value_balance = sum(a.spend_value - a.value for a in bundle.actions)
    return bundle


def _alpha_2_rk(rk_alpha_1):
    return _pallas_point_to_bytes(_pallas_point_add(
        _pallas_point_from_bytes(rk_alpha_1),
        _pallas_point_from_bytes(ORCHARD_SPENDAUTHSIG_BASEPOINT_BYTES),
    ))


# A real spend of a note paid to the account's change address, with a zero-valued output to that
# same address. Generated by gen_internal_spend_vectors in vendor/orchard.
_INTERNAL_SPEND_VALUE = 20000
_INTERNAL_SPEND_RHO = bytes([0x09]) + bytes(31)
_INTERNAL_SPEND_RSEED = bytes([0x1D]) + bytes(31)
_INTERNAL_OUTPUT_RSEED = bytes([0x31]) + bytes(31)
_INTERNAL_RCV = bytes([0x45]) + bytes(31)
_INTERNAL_SPEND_CV_NET = bytes.fromhex("f7a5a5a3e2382d1002407279917b98be540a9af9e81b6e3057e76ee1ee439795")
_INTERNAL_SPEND_NULLIFIER = {
    "orchard": bytes.fromhex("dd2040dce439949930cf281228566c6b4ed2f1c11c94ae09c9aeb451d4f66630"),
    "ironwood": bytes.fromhex("895db3e7f88e7b746f4e5013b01d4cb8f0d2cbb6d83f4b4cf2564f170c031313"),
}
_INTERNAL_SPEND_CMX = {
    "orchard": bytes.fromhex("751a2c9e91b14558602fefb40f977c4d2f08cf9dc12bfe9c483996725463ee11"),
    "ironwood": bytes.fromhex("aa79bb112e20a2c114c2974644260bd7d9f4172b8917d7b297f5b84a316e682c"),
}


def _external_then_internal_spend(pool, dummy_first):
    """An external-scope spend, then one the device can only match through the internal IVK."""
    bundle = _distinct_spends(pool, dummy_first)
    first = bundle.actions[-2]
    action_type = PcztOrchardAction if pool == "orchard" else PcztIronwoodAction
    bundle.actions[-1] = action_type(
        cv_net=_INTERNAL_SPEND_CV_NET,
        nullifier=_INTERNAL_SPEND_NULLIFIER[pool],
        spend_recipient=_INTERNAL_RECIPIENT,
        spend_rho=_INTERNAL_SPEND_RHO,
        spend_rseed=_INTERNAL_SPEND_RSEED,
        rk=_alpha_2_rk(first.rk),
        alpha=(2).to_bytes(32, "little"),
        signing_path=_SIGNING_PATH,
        cmx=_INTERNAL_SPEND_CMX[pool],
        ephemeral_key=bytes(32),
        enc_ciphertext=bytes(580),
        out_ciphertext=bytes(80),
        rcv=_INTERNAL_RCV,
        rseed=_INTERNAL_OUTPUT_RSEED,
        spend_value=_INTERNAL_SPEND_VALUE,
        value=0,
        recipient=_INTERNAL_RECIPIENT,
    )
    bundle.value_balance = sum(a.spend_value - a.value for a in bundle.actions)
    return bundle


def _send_and_verify(client, navigator, pool, bundle):
    global_fields = PcztGlobal() if pool == "orchard" else PCZT_V6_GLOBAL
    outputs = [_TRANSPARENT_OUTPUT_299K]
    with client.send_pczt(
        pczt_global=global_fields, transparent_inputs=[], transparent_outputs=outputs,
        **{f"{pool}_bundle": bundle},
    ):
        _review_approve(navigator, "key_reuse", compare=False)
    digest = None
    if pool == "orchard":
        tx = pczt_transaction_bytes(global_fields, [], outputs, bundle)
        digest = nu5_signature_digests(tx, [])["final_digest"]
    sign = client.pczt_sign_orchard if pool == "orchard" else client.pczt_sign_ironwood
    for index, action in enumerate(bundle.actions):
        if action.spend_value:
            signature = sign(action_index=index).data
            assert len(signature) == 64
            if digest is not None:
                assert check_orchard_spendauth_signature_validity(action.rk, signature, digest)


@pytest.mark.parametrize("pool", ["orchard", "ironwood"])
@pytest.mark.parametrize("dummy_first", [False, True])
def test_pczt_key_reuse_distinct_spends(backend, scenario_navigator, pool, dummy_first):
    client = ZcashCommandSender(backend)
    _send_and_verify(client, scenario_navigator, pool, _distinct_spends(pool, dummy_first))


@pytest.mark.parametrize("pool", ["orchard", "ironwood"])
@pytest.mark.parametrize("dummy_first", [False, True])
def test_pczt_key_reuse_internal_spend_after_external(backend, scenario_navigator, pool, dummy_first):
    client = ZcashCommandSender(backend)
    _send_and_verify(client, scenario_navigator, pool, _external_then_internal_spend(pool, dummy_first))


@pytest.mark.parametrize("pool", ["orchard", "ironwood"])
@pytest.mark.parametrize("field", ["rk", "signing_path"])
def test_pczt_key_reuse_failure_then_new_transaction(backend, scenario_navigator, pool, field):
    client = ZcashCommandSender(backend)
    bundle = _distinct_spends(pool, True)
    if field == "rk":
        bundle.actions[-1].rk = bundle.actions[-2].rk
        expected = Errors.SW_INVALID_TRANSACTION
    else:
        bundle.actions[-1].signing_path = "m/32'/133'/1'"
        expected = Errors.SW_BAD_STATE
    with pytest.raises(ExceptionRAPDU) as error:
        with client.send_pczt(
            pczt_global=PcztGlobal() if pool == "orchard" else PCZT_V6_GLOBAL,
            transparent_inputs=[], transparent_outputs=[_TRANSPARENT_OUTPUT_299K],
            **{f"{pool}_bundle": bundle},
        ):
            pytest.fail("Malformed second spend reached review")
    assert error.value.status == expected and not error.value.data
    _send_and_verify(client, scenario_navigator, pool, _distinct_spends(pool, False))


def _flip_byte(value, index):
    return value[:index] + bytes([value[index] ^ 1]) + value[index + 1:]


_DIVERSIFIER_SIZE = 11


@pytest.mark.parametrize("pool", ["orchard", "ironwood"])
@pytest.mark.parametrize("dummy_first", [False, True])
@pytest.mark.parametrize("field", ["diversifier", "pk_d", "nullifier", "cmx"])
@pytest.mark.parametrize("scope", ["external", "internal"])
def test_pczt_key_reuse_rejects_a_tampered_later_spend(backend, pool, dummy_first, field, scope):
    """The spend validated from cached account keys gets every per-action check."""
    client = ZcashCommandSender(backend)
    if scope == "external":
        bundle = _distinct_spends(pool, dummy_first)
    else:
        bundle = _external_then_internal_spend(pool, dummy_first)
    later = bundle.actions[-1]
    if field == "diversifier":
        later.spend_recipient = _flip_byte(later.spend_recipient, 0)
    elif field == "pk_d":
        later.spend_recipient = _flip_byte(later.spend_recipient, _DIVERSIFIER_SIZE)
    else:
        setattr(later, field, _flip_byte(getattr(later, field), 0))
    with pytest.raises(ExceptionRAPDU) as error:
        with client.send_pczt(
            pczt_global=PcztGlobal() if pool == "orchard" else PCZT_V6_GLOBAL,
            transparent_inputs=[], transparent_outputs=[_TRANSPARENT_OUTPUT_299K],
            **{f"{pool}_bundle": bundle},
        ):
            pytest.fail("Tampered later spend reached review")
    assert error.value.status == Errors.SW_INVALID_TRANSACTION and not error.value.data
